//**CUEBALL**:
//placed by the user when start game or after a foul (including out of bounds).

//__mouse__:when available,the cursor changes to a hand. A "NO" sign appears when hovering outside
//the D-zone or colliding with balls. LEFT-click to place it.

//__keyboard__:Use WASD to move the mouse position in the p5 world,controlling the cue ball.
//However,this is difficult if the ball starts far from the D-zone.I considered moving
//the ball into the D-zone immediately when pressed outside,but this was annoying
//near the boundary.To fix this,"Z" moves the ball into the D-zone,and "X" places it.

//**CUE**

//__mouse__:Drag with LEFT-click to control the cue's position.

//__keyboard__:Press “UP/DOWN” to control the cue angle continuously while holding the button.
// Press “LEFT/RIGHT” for small angle adjustments,ideal for precise positioning.

//__Shoot__:Right-click or press Space Bar to enable force control,then click again to shoot.

//The cue is not part of the engine world until shooting.Applying force by matter.js to
//the cue ball based on the cue angle.Initially,I added sleeping and awake states in Matter.js
//but found them unnecessary and causing more memory.I removed these and now display a virtual cue,
//applying physics only during shooting.This also avoids unintended interactions with other balls.

//=======Random algorithm=======

//3 Types balls in the pool(red, colour, cue),generated by function with “isRandom” option.
//Each mode random one more sets by sequence.The mode number determines a Boolean value for
//the generation function, reducing duplicate code and supporting extensions.

//**Algorithm**
//When isRandom is passed to the shared function randomPos, it returns a randomVector.
//Inside, X and Y values are generated using p5.js random()(ranging from zero to the tableSize).
//I chose this over Perlin noise as it is more separable and better matches the expectation of randomness.

//**Duplication**
//The vector is recursively checked by“isCollidingWithOtherBalls”to avoid duplication.
//However,checking one by one affects the next.So,all balls are removed and regenerated before execution.

//__Excldeing cueBall__:in all modes and placed back in the D-zone [including DragonBall character mode].

//=======Extension=======

//**Dragon Ball**:

//Every potted ball(including the cueBall for player strategy) is considered a dragon ball.
//Collecting 7 balls summons the dragon(the cloud and dragon will come up),
//allowing a wish that can change the game state.

//__Cloud__:Initially, I used Perlin noise for the cloud,but it caused lag.Changing the seed or
//noise detail didn’t help because Perlin noise modifies every pixel.Skipping pixels in the loop
//caused striped patterns,and skipping frames made the cloud flash.Eventually, I replaced
//pixel-level rendering with circles,significantly reducing rendering load and solving the problem.

